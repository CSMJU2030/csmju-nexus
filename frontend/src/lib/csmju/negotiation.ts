/// กฎตัดสินเมื่อสองฝั่งยื่นข้อเสนอ WebRTC ชนกัน (perfect negotiation)
///
/// **ทำไมต้องแยกออกมาเป็นฟังก์ชันล้วน**
///
/// ตรรกะนี้สั้นมากแต่พังแล้วหาไม่เจอ: ถ้าตัดสินผิด สายจะค้างที่
/// `have-local-offer` ทั้งสองฝั่ง **ถาวร** โดยไม่มี error ออกมาสักตัว
/// อาการที่ผู้ใช้เห็นคือ "กำลังต่อสาย…" ค้างอยู่เฉย ๆ ซึ่งแยกไม่ออกจาก
/// เน็ตช้า จึงต้องพิสูจน์ด้วยเทสต์ให้ได้ ไม่ใช่รอเจอหน้างาน
///
/// ตรรกะนี้อยู่ในตัวรับสัญญาณของหน้าห้องเสียง ซึ่งต้องมี socket จริง
/// ไมค์จริง และ RTCPeerConnection จริงถึงจะเรียกได้ — แยกออกมาแล้ว
/// ทดสอบทุกกรณีได้ตรง ๆ

/// เราเป็นฝ่ายที่ "ยอมถอย" ของสายนี้ไหม
///
/// ต้องได้ผล **ตรงข้ามกันเสมอ** เมื่อทั้งสองฝั่งคำนวณด้วย id คู่เดียวกัน
/// ไม่งั้นจะเกิดสองกรณีที่พังทั้งคู่:
///
///   - ยอมถอยทั้งคู่  → ทั้งคู่ทิ้งข้อเสนอตัวเอง ไม่มีใครได้ต่อ
///   - ไม่ยอมถอยทั้งคู่ → ทั้งคู่เมินของอีกฝ่าย สายค้างถาวร
///
/// การเทียบ id ให้ผลตรงข้ามกันโดยอัตโนมัติและไม่ต้องคุยกันก่อน
export function isPolite(myCoreUserId: string, theirCoreUserId: string) {
  return myCoreUserId > theirCoreUserId;
}

/// สถานะของสายเท่าที่กฎนี้ต้องรู้
export interface OfferContext {
  /// เรายอมถอยของสายนี้ไหม (จาก `isPolite`)
  polite: boolean;
  /// เรากำลังยื่นข้อเสนอของเราเองอยู่
  makingOffer: boolean;
  /// สถานะจริงของ `RTCPeerConnection`
  signalingState: RTCSignalingState;
}

/// ข้อเสนอที่เข้ามา "ชน" กับของเราไหม
///
/// ชนได้สองแบบ: เรากำลังสร้างข้อเสนออยู่ (ยังไม่ทันส่ง) หรือส่งไปแล้วและ
/// กำลังรอคำตอบ (`have-local-offer`) — ทั้งสองแบบอันตรายเท่ากัน
export function isCollision({
  makingOffer,
  signalingState,
}: Pick<OfferContext, 'makingOffer' | 'signalingState'>) {
  return makingOffer || signalingState !== 'stable';
}

/// ต้องเมินข้อเสนอที่เข้ามาไหม
///
/// เมินเฉพาะตอนที่ชนกัน **และ** เราเป็นฝ่ายที่ไม่ยอมถอย อีกฝั่งจะทิ้งของเขา
/// แล้วมารับของเราแทน — ได้ข้อสรุปเดียวกันทั้งคู่โดยไม่ต้องตกลงกันก่อน
export function shouldIgnoreOffer(context: OfferContext) {
  return !context.polite && isCollision(context);
}
